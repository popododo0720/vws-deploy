#!/usr/bin/env bash
# summary: open the nightly PR that carries the regenerated feature map and links the run log
# Sourced by scripts/vws. Usage: vws nightly-pr --results DIR --log-url URL [--root DIR] [--repo OWNER/NAME]
#   [--remote NAME]
# vws-deploy#290 AC2 (Part of #252). Runs after `vws nightly` has rewritten docs/feature-map.{json,md}
# in the checkout at --root (default this repo). Commits only those two files, on top of the checkout's
# HEAD, to the branch nightly/<run> (<run> is the basename of DIR, e.g. 20261031T130000Z), pushes only
# that branch and opens one PR into main whose body says Part of #252, links URL and lists every
# result in DIR. It never pushes to main and never changes the checkout's branch, index or files.
# Rerunning the same run is safe: a pushed branch with the same files is reused, and an open PR for the
# branch is reported instead of opened again. Publishing the log behind URL is a separate step (AC 6).
# Exit: 0 PR opened or already open, or the map is unchanged (WARN); 1 the push or the PR failed;
# 2 usage; 3 environment (tool missing, --root not a git checkout).
# shellcheck disable=SC2034 # read by scripts/vws
VWS_NEED=(git gh jq)

vws_nightly_pr_body() { # RUN LOG_URL DIR: the PR body on stdout
  local f
  printf 'Part of #252\n\nNightly feature-map run %s on vws-test.\n\nRun log: %s\n\n' "$1" "$2"
  printf '| Scenario | Result | Finished | Evidence |\n|---|---|---|---|\n'
  for f in "$3"/*.json; do
    [[ -f $f ]] || continue
    jq -r '"| \(.scenario // "?" | tostring | gsub("[|\n]"; " ")) | \(.result // "?" | tostring | gsub("[|\n]"; " "))'`
      `' | \(.finishedAt // "" | tostring | gsub("[|\n]"; " ")) | \(.evidence // "" | tostring | gsub("[|\n]"; " ")) |"' \
      "$f" 2>/dev/null || printf '| %s | unreadable result | | |\n' "$(basename "$f" .json)"
  done
  printf '\nOnly a vws-test pass moves a feature'"'"'s last pass forward. Generated by vws nightly-pr.\n'
}

vws_cmd_main() {
  local root=$VWS_ROOT results='' log_url='' repo=popododo0720/vws-deploy remote=origin
  local run branch parent tree commit idx url out rc
  local -a files=(docs/feature-map.json docs/feature-map.md)
  while (($#)); do
    case $1 in
      --root | --results | --log-url | --repo | --remote)
        (($# >= 2)) || vws_usage "$1 needs a value"
        case $1 in
          --root) root=$2 ;;
          --results) results=$2 ;;
          --log-url) log_url=$2 ;;
          --repo) repo=$2 ;;
          --remote) remote=$2 ;;
        esac
        shift 2 ;;
      *) vws_usage "nightly-pr: unknown argument $1" ;;
    esac
  done
  [[ -n $results ]] || vws_usage "nightly-pr needs --results DIR (the vws nightly run directory)"
  [[ $log_url =~ ^https://[^[:space:]\`\<\>]{1,2000}$ ]] || vws_usage "--log-url must be an https URL without spaces"
  [[ $repo =~ ^[A-Za-z0-9-]{1,39}/[A-Za-z0-9._-]{1,100}$ ]] || vws_usage "--repo must be OWNER/NAME, not ${repo}"
  [[ $remote =~ ^[A-Za-z0-9._-]{1,64}$ ]] || vws_usage "--remote must be a remote name, not ${remote}"
  run=$(basename "$results")
  [[ $run =~ ^[0-9]{8}T[0-9]{6}Z$ ]] || vws_usage "--results must be a run directory named like 20261031T130000Z, not ${run}"
  [[ -d $results ]] || vws_usage "--results ${results} is not a directory"
  branch="nightly/${run}"
  case $branch in main | master | refs/heads/main | refs/heads/master) vws_die_env "internal: refusing to push to ${branch}" ;; esac

  [[ $(git -C "$root" rev-parse --show-toplevel 2>/dev/null) == "$(cd "$root" && pwd -P)" ]] ||
    vws_die_env "--root ${root} is not the top of a git checkout"
  if [[ -z $(git -C "$root" status --porcelain -- "${files[@]}") ]]; then
    vws_emit WARN nightly-pr "feature map unchanged against HEAD; no PR opened"
    return 0
  fi

  # The commit is built in a private index so the checkout's own branch, index and files stay as they are.
  idx=$(mktemp) || vws_die_env "cannot create a temporary index"
  rc=0
  {
    GIT_INDEX_FILE=$idx git -C "$root" read-tree HEAD &&
      GIT_INDEX_FILE=$idx git -C "$root" update-index --add -- "${files[@]}" &&
      tree=$(GIT_INDEX_FILE=$idx git -C "$root" write-tree)
  } 2>/dev/null || rc=$?
  rm -f "$idx"
  ((rc == 0)) || vws_die_env "cannot stage ${files[*]} in ${root}"

  parent=$(git -C "$root" rev-parse HEAD)
  if git -C "$root" fetch -q "$remote" "+refs/heads/${branch}:refs/remotes/${remote}/${branch}" 2>/dev/null; then
    parent=$(git -C "$root" rev-parse "refs/remotes/${remote}/${branch}")
  fi
  if [[ $(git -C "$root" rev-parse "${parent}^{tree}") == "$tree" ]]; then
    commit=$parent
    vws_emit OK nightly-pr "branch ${branch} already holds this feature map"
  else
    commit=$(printf 'docs: record the nightly feature-map results (%s)\n\nRun log: %s\n\nPart of #252\n' "$run" "$log_url" |
      git -C "$root" commit-tree "$tree" -p "$parent") || vws_die_env "cannot create the nightly commit"
    rc=0; out=$(git -C "$root" push -q "$remote" "${commit}:refs/heads/${branch}" 2>&1) || rc=$?
    if ((rc != 0)); then
      vws_emit FAIL nightly-pr "push of ${branch} failed: ${out:0:300}"
      return 0
    fi
    vws_emit OK nightly-pr "pushed ${commit:0:12} to ${branch}"
  fi

  rc=0; url=$(gh pr list --repo "$repo" --head "$branch" --state open --json url -q '.[0].url // ""' 2>&1) || rc=$?
  if ((rc != 0)); then
    vws_emit FAIL nightly-pr "cannot list PRs for ${branch}: ${url:0:300}"
    return 0
  fi
  if [[ -n $url ]]; then
    vws_emit OK nightly-pr "PR already open: ${url}"
    return 0
  fi
  local body; body=$(mktemp) || vws_die_env "cannot create a temporary PR body"
  vws_nightly_pr_body "$run" "$log_url" "$results" >"$body"
  rc=0
  out=$(gh pr create --repo "$repo" --base main --head "$branch" \
    --title "docs: nightly feature-map results ${run}" --body-file "$body" 2>&1) || rc=$?
  rm -f "$body"
  if ((rc != 0)); then
    vws_emit FAIL nightly-pr "PR create for ${branch} failed: ${out:0:300}"
    return 0
  fi
  vws_emit OK nightly-pr "opened ${out##*$'\n'}"
}
